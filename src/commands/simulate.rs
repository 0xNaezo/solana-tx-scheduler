//! Power analysis: how many windows per validator does the pre-registered
//! classifier need to name the right rule, and how often does it invent one
//! on pure noise? Same code path as `analyze`, synthetic windows.

use std::{fmt::Write as _, fs, thread};

use anyhow::Result;
use rand::{SeedableRng, rngs::StdRng};

use crate::{
    cli::SimulateArgs,
    stats::{
        self, Label, SYNTH_JITTER_MS, SYNTH_SLOT_MS, Truth, classify, estimate_n, holm, model_fit,
        synth_window, treatment_cells,
    },
};

/// Fewer than `analyze` uses, to keep the run short; coarser p-values only
/// make the simulated power conservative.
const PERMUTATIONS: usize = 2_000;
/// Landing probability of each transaction.
const LAND: f64 = 0.8;
const PAUSES: [u64; 3] = [0, 10, 50];

/// Share of runs labelled correctly, the mean estimated D, and the median
/// batch length of the runs labelled as batched (NaN if none).
pub fn power(
    truth: Truth,
    noise: f64,
    windows: usize,
    args: &SimulateArgs,
    seed: u64,
) -> (f64, f64, f64) {
    let n = args.txs_per_window;
    let (mut hits, mut d_sum, mut d_n) = (0, 0.0, 0);
    let mut periods: Vec<u64> = Vec::new();
    for r in 0..args.reps {
        let mut rng = StdRng::seed_from_u64(seed.wrapping_mul(1_000_003) + r as u64);
        let cells = treatment_cells(&PAUSES, &mut rng);
        let ws: Vec<_> = (0..windows)
            .map(|k| synth_window(truth, cells[k % cells.len()], n, noise, LAND, &mut rng))
            .collect();
        let e = estimate_n(&ws, r as u64, PERMUTATIONS);
        if !e.d.value.is_nan() {
            d_sum += e.d.value;
            d_n += 1;
        }
        // Holm over the whole run's family, the other validators showing no
        // effect: the worst case for this one.
        let mut family = vec![1.0; 2 * args.validators.max(1)];
        family[..2].copy_from_slice(&[e.p_d, e.p_a]);
        let adj = holm(&family);
        let label = classify(&e, adj[0], adj[1], &model_fit(&ws));
        if let Label::BatchedPriority(t) = label {
            periods.push(t);
        }
        hits += usize::from(truth.accepts(label));
    }
    periods.sort_unstable();
    let median = periods
        .get(periods.len() / 2)
        .map_or(f64::NAN, |&t| t as f64);
    (
        hits as f64 / args.reps as f64,
        d_sum / d_n.max(1) as f64,
        median,
    )
}

pub fn execute(args: SimulateArgs) -> Result<()> {
    let truths = [
        ("priority", Truth::Priority),
        ("FIFO", Truth::Fifo),
        ("priority within 20 ms batches", Truth::Batched(20)),
        ("priority within 50 ms batches", Truth::Batched(50)),
        ("noise (negative control)", Truth::Noise),
    ];
    let noises = [0.05, 0.15, 0.25];
    let rows: Vec<(String, Vec<f64>)> = thread::scope(|s| {
        let handles: Vec<_> = truths
            .iter()
            .flat_map(|&(name, truth)| noises.iter().map(move |&noise| (name, truth, noise)))
            // Noise ignores the noise level: one row is enough.
            .filter(|&(_, truth, noise)| truth != Truth::Noise || noise == noises[0])
            .map(|(name, truth, noise)| {
                let args = &args;
                s.spawn(move || {
                    let runs: Vec<(f64, f64, f64)> = args
                        .windows
                        .iter()
                        .map(|&w| power(truth, noise, w, args, w as u64))
                        .collect();
                    let (_, mean_d, median_t) =
                        runs.last()
                            .copied()
                            .unwrap_or((f64::NAN, f64::NAN, f64::NAN));
                    let mut label = if truth == Truth::Noise {
                        format!("{name}, mean D {mean_d:.2}")
                    } else {
                        format!("{name}, noise sd {noise}, mean D {mean_d:.2}")
                    };
                    if matches!(truth, Truth::Batched(_)) {
                        let _ = write!(label, ", median estimated batch {median_t:.0} ms");
                    }
                    (label, runs.into_iter().map(|r| r.0).collect())
                })
            })
            .collect();
        handles
            .into_iter()
            .map(|h| h.join().expect("simulation thread"))
            .collect()
    });

    let mut md = String::new();
    let _ = writeln!(md, "# Power analysis (synthetic windows)\n");
    let _ = writeln!(
        md,
        "Generated by `solana-tx-scheduler simulate --reps {} --txs-per-window {} --validators {}`.\n\n\
         - Each window: {} transactions on the priority ladder, design cells cycled as in `run` (send order reverse/random \
         × pauses {} ms × shared/distinct payer).\n\
         - A transaction reaches the leader at its send time plus Gaussian jitter (sd {SYNTH_JITTER_MS} ms), so pause-0 \
         transactions arrive in random order. It lands with p={LAND}, in the slot its arrival falls into: slots are \
         {SYNTH_SLOT_MS} ms long at a random phase, so a 50 ms-pause batch spans 3 slots.\n\
         - Within a slot, the order is the rule's score plus Gaussian noise (sd on a 0..1 priority scale; adjacent ladder \
         steps are {:.2} apart). FIFO means arrival order at the leader.\n\
         - p-values from {PERMUTATIONS} permutations (`analyze` uses {}). Holm runs over 2 × {} tests, with the other \
         validators showing no effect, which is the worst case.\n\
         - A cell is the share of runs where the pre-registered classifier returned the true label. For batching, that is the \
         batched label with a fitted batch length within a factor of 1.5 of the true one. For noise, it is 1 − false-rule rate.\n\
         - Mean D is the estimate at the largest window count. Where it sits near the 0.8 / 0.2 thresholds the truth itself \
         is borderline, and a \"mixed\" label reports lower strictness rather than missing the direction.\n",
        args.reps,
        args.txs_per_window,
        args.validators,
        args.txs_per_window,
        PAUSES.map(|p| p.to_string()).join(", "),
        1.0 / (args.txs_per_window.max(2) - 1) as f64,
        stats::PERMUTATIONS,
        args.validators,
    );
    let head: Vec<String> = args
        .windows
        .iter()
        .map(|w| format!("{w} windows"))
        .collect();
    let _ = writeln!(
        md,
        "| true rule | {} |\n|---|{}",
        head.join(" | "),
        "---|".repeat(head.len())
    );
    for (label, cells) in &rows {
        let c: Vec<String> = cells.iter().map(|p| format!("{:.0}%", p * 100.0)).collect();
        let _ = writeln!(md, "| {label} | {} |", c.join(" | "));
    }
    if let Some(dir) = args.out.parent() {
        fs::create_dir_all(dir)?;
    }
    fs::write(&args.out, &md)?;
    print!("{md}");
    Ok(())
}
